import { MAX_PHOTO_DATA_URL_LENGTH } from './limits';

const SCHEME_PATTERN = /^[a-z][a-z\d+.-]*:/iu;

/** Return a normalized HTTP(S) URL suitable for an external link, or undefined. */
export const normalizeExternalUrl = (value: string | null | undefined): string | undefined => {
  const trimmed = value?.trim();
  if (!trimmed) return undefined;

  try {
    const candidate = SCHEME_PATTERN.test(trimmed) ? trimmed : `https://${trimmed}`;
    const url = new URL(candidate);
    if (url.protocol !== 'https:' && url.protocol !== 'http:') return undefined;
    if (!url.hostname || url.username || url.password) return undefined;
    return url.href;
  } catch {
    return undefined;
  }
};

/** Only permit local, raster image data generated by the image uploader. */
export const normalizePhotoDataUrl = (value: string | null | undefined): string | undefined => {
  if (!value || value.length > MAX_PHOTO_DATA_URL_LENGTH) return undefined;
  return /^data:image\/(?:jpeg|png|webp|gif);base64,[a-z\d+/]+=*$/iu.test(value)
    ? value
    : undefined;
};
